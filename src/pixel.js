// Icone a pixel disegnate a mano, 16x16: souvenir romani e oggetti del taccuino.
// Ogni disegno e una griglia di caratteri: "." vuoto, "*" luce (acqua, vapore, scintille: niente bordo),
// ogni altra lettera un colore della sua tavolozza. Il bordo d'inchiostro si aggiunge da solo.
const INCHIOSTRO = '#2a1f16';
const BUIO = '#4a3b2e';

export function pixel(nome, { buio = false } = {}) {
  const { disegno: g, colori } = ICONE[nome];
  const h = g.length, w = g[0].length;
  const cella = (x, y) => (y >= 0 && y < h && x >= 0 && x < w ? g[y][x] : '.');
  const pieno = (x, y) => { const c = cella(x, y); return c !== '.' && c !== '*'; };
  const runs = [];
  for (let y = -1; y <= h; y++) {
    let prima = null, da = 0;
    for (let x = -1; x <= w + 1; x++) {
      const c = cella(x, y);
      let col = null;
      if (c === '*') col = buio ? null : colori['*'];
      else if (c !== '.') col = buio ? BUIO : colori[c];
      else if (pieno(x + 1, y) || pieno(x - 1, y) || pieno(x, y + 1) || pieno(x, y - 1)) col = buio ? BUIO : INCHIOSTRO;
      if (col !== prima) {
        if (prima) runs.push(`<rect x="${da + 1}" y="${y + 1}" width="${x - da}" height="1" fill="${prima}"/>`);
        prima = col; da = x;
      }
    }
  }
  return `<svg viewBox="0 0 ${w + 2} ${h + 2}" shape-rendering="crispEdges" aria-hidden="true">${runs.join('')}</svg>`;
}

